# Per-picture framing (2026-10-15, Sevaan: "not all of the cards need the images lowered… use some judgement").
# For each card picture, find where its subject starts (first row with a real share of bright, non-star pixels) and
# lower it only as much as it needs to clear the rarity/set chips: shift = 15% - top, at most 12%, never negative.
# Writes js/art-frame.js: ART_SHIFT = { file: percent }. Run after scripts/import-art.py (and for preview art dirs).
import glob, os, sys, json, numpy as np
from PIL import Image
def extent(path):
  # top and bottom of the subject, as fractions of the height of the 4:3 card window (the picture is cover-cropped to it)
  im = Image.open(path).convert('L'); w, h = im.size; cw = h * 4 / 3
  if cw < w: im = im.crop((int((w - cw) / 2), 0, int((w + cw) / 2), h))
  a = np.asarray(im.resize((300, 225))).astype(float)
  bg = np.median(a[:6]); rows = ((a > max(70, bg + 45))).mean(axis=1)
  hit = [y for y in range(len(rows)) if 0.04 < rows[y] < 0.62]  # very wide rows are Earth's limb, not the subject
  return (hit[0] / len(rows), hit[-1] / len(rows)) if hit else (1, 0)
dirs = sys.argv[1:] or ['assets/art/cards']
out = {}
for d in dirs:
  for f in sorted(glob.glob(os.path.join(d, '*.webp'))):
    n = os.path.basename(f)[:-5]; t, b = extent(f); s = round(min(12, max(0, (0.15 - t) * 100), max(0, (0.94 - b) * 100)), 1) # never push the subject's bottom out of the window
    if s >= 1: out[n] = s
js = '// Generated by scripts/art-frame.py: how far (%) each picture is lowered in the card window so its subject clears the chips.\nexport const ART_SHIFT = ' + json.dumps(out, separators=(',', ':')) + ';\n'
open('js/art-frame.js' if dirs == ['assets/art/cards'] else os.path.join(dirs[0], 'frame.js'), 'w').write(js)
print(len(out), 'lowered of', sum(len(glob.glob(os.path.join(d, '*.webp'))) for d in dirs)); print(out)
