function inside([x, y], poly) {
  let c = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
}
// lat, lon in degrees (lon −180…180). Returns e.g. "Africa", "the North Atlantic", "Antarctica".
export function placeName(lat, lon) {
  lon = ((lon + 540) % 360) - 180;
  if (lat <= -66) return 'Antarctica';
  for (const [name, poly] of LAND) if (inside([lon, lat], poly)) return name;
  if (lat >= 66) return 'the Arctic Ocean';
  if (lat <= -58) return 'the Southern Ocean';
  if (lon > -6 && lon < 36 && lat > 30 && lat < 46) return 'the Mediterranean';
  if (lon > -98 && lon < -81 && lat > 18 && lat < 31) return 'the Gulf of Mexico';
  if (lon > -88 && lon < -60 && lat > 9 && lat < 22) return 'the Caribbean';
  const half = lat >= 0 ? 'North' : 'South';
  if ((lat > 8 && lon > -82 && lon < 20) || (lat <= 8 && lon > -70 && lon < 20)) return `the ${half} Atlantic`;
  if (lon >= 20 && lat < 30 && lon <= (lat > -11 ? 105 : 147)) return 'the Indian Ocean';
  return `the ${half} Pacific`;
}
